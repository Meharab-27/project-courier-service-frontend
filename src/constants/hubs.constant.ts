/**
 * Merge hubs fetched from API with the fallback ALL_HUBS so that:
 * 1. Database-backed hubs preserve their primary keys (id) and timestamps
 * 2. Any hubs defined in seed data that are missing or if the API is offline are seamlessly included
 */
export function mergeHubsWithDefaults(apiHubs?: IHub[]): IHub[] {
  const map = new Map<string, IHub>();

  // First populate with all 62 predefined hubs
  for (const hub of ALL_HUBS) {
    if (hub.code) {
      map.set(hub.code.toUpperCase().trim(), hub);
    }
  }

  // Then merge / overlay any live data from the database
  if (Array.isArray(apiHubs)) {
    for (const hub of apiHubs) {
      if (hub.code) {
        const codeKey = hub.code.toUpperCase().trim();
        const existing = map.get(codeKey);
        map.set(codeKey, { ...existing, ...hub });
      } else if (hub.id) {
        map.set(hub.id, hub);
      }
    }
  }

  return Array.from(map.values());
}

